const { chromium } = require('playwright');
const fs = require('node:fs/promises');
(async () => {
  await fs.mkdir('preview-screens', { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4173', { waitUntil: 'networkidle' });
  await page.getByText('Aynı hikâyenin').waitFor();
  await page.screenshot({ path: 'preview-screens/01-welcome.png' });
  await page.getByText('Örnek dünyayı keşfet', { exact: false }).click();
  await page.getByRole('tab', { name: 'Harita', exact: true }).waitFor();
  await page.locator('.leaflet-container').waitFor();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: 'preview-screens/02-map.png' });
  await page.getByRole('tab', { name: 'Mesajlar', exact: true }).click();
  await page.getByText('Küçük mesajlar, güzel yakınlıklar.').waitFor();
  await page.screenshot({ path: 'preview-screens/03-messages.png' });
  await page.getByRole('tab', { name: 'Albüm', exact: true }).click();
  await page.getByText('3 ortak anı').waitFor();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: 'preview-screens/04-album.png' });
  await page.getByRole('button', { name: 'Ayarlar ve konum paylaşımı' }).click();
  await page.getByText('Sana ait kontroller').waitFor();
  await page.screenshot({ path: 'preview-screens/05-settings.png' });
  await fs.writeFile('preview-screens/result.json', JSON.stringify({ viewport: '390x844', mode: 'actual mobile web preview; simulated sample locations', pageErrors: errors }, null, 2));
  if (errors.length) throw new Error('App runtime errors: ' + errors.join('; '));
  await browser.close();
})();
